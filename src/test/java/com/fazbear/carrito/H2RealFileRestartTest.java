package com.fazbear.carrito;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.math.BigDecimal;
import java.nio.file.Path;
import java.sql.*;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Verificación técnica rigurosa de persistencia H2 basada en archivo.
 * Demuestra la conservación de datos entre conexiones independientes y
 * cierres completos de la base de datos (simulando reinicios reales de la aplicación).
 */
class H2RealFileRestartTest {

    @TempDir
    Path tempDir;

    @Test
    @DisplayName("H2 en modo archivo debe persistir datos tras cierre total de conexiones y reapertura")
    void testH2FilePersistsDataAcrossIndependentConnections() throws SQLException {
        // Path al archivo de base de datos en almacenamiento persistente (simula volumen EBS)
        Path dbFile = tempDir.resolve("carritodb");
        // DB_CLOSE_DELAY=0 fuerza el cierre completo de la base de datos al cerrar la última conexión (simula detención de JVM)
        String jdbcUrl = "jdbc:h2:file:" + dbFile.toAbsolutePath() + ";AUTO_SERVER=FALSE;DB_CLOSE_DELAY=0";

        // =========================================================================
        // SESIÓN 1: Primera ejecución de la aplicación (creación de esquema e inserción)
        // =========================================================================
        try (Connection conn = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            assertThat(conn).isNotNull();
            try (Statement stmt = conn.createStatement()) {
                // Crear tablas según el modelo de Carrito e ItemCarrito
                stmt.execute("""
                    CREATE TABLE carritos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        usuario_id VARCHAR(100) NOT NULL UNIQUE,
                        creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """);
                stmt.execute("""
                    CREATE TABLE items_carrito (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        carrito_id BIGINT NOT NULL,
                        producto_id BIGINT NOT NULL,
                        nombre_producto VARCHAR(120),
                        cantidad INT NOT NULL,
                        precio_unitario DECIMAL(10, 2) NOT NULL,
                        CONSTRAINT fk_carrito FOREIGN KEY (carrito_id) REFERENCES carritos(id)
                    )
                """);

                // Insertar carrito y dos ítems
                stmt.execute("INSERT INTO carritos (usuario_id) VALUES ('user-ebs-test-001')");
                stmt.execute("INSERT INTO items_carrito (carrito_id, producto_id, nombre_producto, cantidad, precio_unitario) VALUES (1, 101, 'Pizza Fazbear Especial', 2, 14.99)");
                stmt.execute("INSERT INTO items_carrito (carrito_id, producto_id, nombre_producto, cantidad, precio_unitario) VALUES (1, 102, 'Refresco Grande', 1, 3.50)");
            }
        }
        // En este punto conn está cerrado, la base de datos H2 se cerró completamente en disco.
        // Se simula el reinicio de la instancia / recreación del contenedor.

        // =========================================================================
        // SESIÓN 2: Segunda ejecución independiente (reinicio real contra el mismo archivo)
        // =========================================================================
        try (Connection conn2 = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            assertThat(conn2).isNotNull();
            try (Statement stmt = conn2.createStatement()) {
                // Verificar que el carrito persiste
                try (ResultSet rs = stmt.executeQuery("SELECT id, usuario_id FROM carritos WHERE usuario_id = 'user-ebs-test-001'")) {
                    assertThat(rs.next()).isTrue();
                    assertThat(rs.getLong("id")).isEqualTo(1L);
                    assertThat(rs.getString("usuario_id")).isEqualTo("user-ebs-test-001");
                }

                // Verificar que los ítems y los cálculos persisten exactamente
                try (ResultSet rs = stmt.executeQuery("""
                    SELECT COUNT(*) AS total_items, SUM(cantidad * precio_unitario) AS gran_total
                    FROM items_carrito
                    WHERE carrito_id = 1
                """)) {
                    assertThat(rs.next()).isTrue();
                    assertThat(rs.getInt("total_items")).isEqualTo(2);
                    assertThat(rs.getBigDecimal("gran_total")).isEqualByComparingTo(new BigDecimal("33.48"));
                }
            }
        }

        // =========================================================================
        // SESIÓN 3: Simulación de comportamiento Hibernate ddl-auto=update
        // Nuevas inserciones deben convivir con los datos persistidos sin borrarlos
        // =========================================================================
        try (Connection conn3 = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            try (Statement stmt = conn3.createStatement()) {
                stmt.execute("INSERT INTO carritos (usuario_id) VALUES ('user-ebs-test-002')");
                try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) AS total_carritos FROM carritos")) {
                    assertThat(rs.next()).isTrue();
                    assertThat(rs.getInt("total_carritos")).isEqualTo(2);
                }
            }
        }
    }
}
